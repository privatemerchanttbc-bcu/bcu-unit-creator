    static String toEnglish(String raw) {
        if (raw == null) return "";
        String s = TAG.matcher(raw).replaceAll(" ");
        StringBuilder w = new StringBuilder(s.length());
        for (int k = 0; k < s.length(); k++) {
            char c = s.charAt(k);
            if ((c >= '\uff10' && c <= '\uff19')
                    || (c >= '\uff21' && c <= '\uff3a')
                    || (c >= '\uff41' && c <= '\uff5a')) c -= 0xfee0;
            w.append(c);
        }
        s = w.toString();
        s = EXT.matcher(s).replaceAll(" ");
        s = LEAD_NUM.matcher(s.trim()).replaceFirst("");
        for (int k = 0; k < SEP.length(); k++) s = s.replace(SEP.charAt(k), ' ');

        StringBuilder out = new StringBuilder();
        int i = 0;
        while (i < s.length()) {
            String en = null;
            int hit = 0;
            for (int k = 0; k < KEYS.length; k++) {
                if (s.startsWith(KEYS[k], i)) { en = MAP.get(KEYS[k]); hit = KEYS[k].length(); break; }
            }
            if (en != null) {
                out.append(' ').append(en).append(' ');
                i += hit;
            } else {
                out.append(s.charAt(i));
                i++;
            }
        }

        String r = SPACES.matcher(out.toString()).replaceAll(" ").trim();
        if (r.isEmpty()) return raw.trim();
        return titleCase(r);
    }

    private static String titleCase(String s) {
        StringBuilder sb = new StringBuilder(s.length());
        boolean head = true;
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            if (c == ' ') { head = true; sb.append(c); continue; }
            if (head && c >= 'a' && c <= 'z') sb.append(Character.toUpperCase(c));
            else sb.append(c);
            head = false;
        }
        return sb.toString();
    }

    static boolean looksForeign(String s) {
        if (s == null) return false;
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            if (c >= 0x3040 && c <= 0x30ff) return true;
            if (c >= 0x3400 && c <= 0x9fff) return true;
            if (c >= 0xac00 && c <= 0xd7af) return true;
        }
        return false;
    }
